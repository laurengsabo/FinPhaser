#!/usr/bin/env python3
"""
bin/generate_spore_settings.py
================================
Generates SPORE-Settings.R from samples.yml.

Called automatically by the Nextflow RUN_SPORE process.

Naming format differences handled here:
  - VCF / popinfo sample names use underscores: YH_006_f, YH_011_m, YH_016
  - Genomics_Sex.tsv uses a compact format: YH006f, YH011m, YH016
  - SPORE cannot handle underscores in sample names

This script documents both discrepancies in the generated
SPORE-Settings.R so that SPORE.R can apply the appropriate
sanitisation at run time.

Usage (called by Nextflow — not normally run directly):
    python bin/generate_spore_settings.py \\
        --vcf          YHPed1_conserved_phased.vcf \\
        --samples-yml  config/samples.yml           \\
        --out          SPORE-Settings.R
"""

import argparse
import sys
from pathlib import Path

import yaml


def parse_args():
    p = argparse.ArgumentParser(description="Generate SPORE-Settings.R from samples.yml")
    p.add_argument("--vcf",         required=True, help="Path to phased VCF")
    p.add_argument("--samples-yml", required=True, help="Path to samples.yml")
    p.add_argument("--out",         default="SPORE-Settings.R")
    return p.parse_args()


def main():
    args = parse_args()

    yml_path = Path(args.samples_yml)
    if not yml_path.exists():
        sys.exit(f"ERROR: samples.yml not found: {yml_path}")

    with open(yml_path) as fh:
        cfg = yaml.safe_load(fh)

    spore_cfg  = cfg.get("spore", {})
    sex_meta   = spore_cfg.get("sex_metadata", "")
    out_prefix = spore_cfg.get("output_prefix", "brood1_final")

    if not sex_meta:
        sys.exit("ERROR: spore.sex_metadata is not set in samples.yml")

    vcf_path  = Path(args.vcf).resolve()
    meta_path = Path(sex_meta).resolve()

    if not vcf_path.exists():
        sys.exit(f"ERROR: VCF not found: {vcf_path}")
    if not meta_path.exists():
        sys.exit(f"ERROR: sex_metadata file not found: {meta_path}")

    # ── Identify samples with underscores (SPORE cannot handle these) ─────────
    populations = cfg.get("populations", [])
    underscore_samples = [
        e["sample"] for e in populations if "_" in e["sample"]
    ]
    if underscore_samples:
        unique_flagged = sorted(set(underscore_samples))
        print(
            f"[generate_spore_settings] NOTE: {len(unique_flagged)} unique sample "
            f"name(s) contain underscores — SPORE.R must sanitise these before "
            f"running SPORE.\n  Flagged: {unique_flagged}",
            file=sys.stderr,
        )

    # ── Write SPORE-Settings.R ────────────────────────────────────────────────
    settings_r = f"""\
# SPORE-Settings.R
# Auto-generated by FinPhaser pipeline (bin/generate_spore_settings.py)
# Do not edit manually — this file is regenerated on each pipeline run.

# ── Input files ───────────────────────────────────────────────────────────────
vcf_file     <- "{vcf_path}"
sex_metadata <- "{meta_path}"
output_prefix <- "{out_prefix}"

# ── Naming format notes ───────────────────────────────────────────────────────
# VCF sample names use underscores:   YH_006_f, YH_011_m, YH_016, ...
# Genomics_Sex.tsv uses compact names: YH006f,   YH011m,   YH016,  ...
# SPORE cannot handle underscores in sample IDs.
#
# SPORE.R should:
#   1. Strip underscores from VCF sample names before passing to SPORE.
#   2. When joining with sex_metadata, match on the compact form
#      (remove underscores and trailing sex-letter suffix from VCF names,
#       or use a lookup table).
#
# Samples flagged as having underscores:
#   {', '.join(sorted(set(underscore_samples))) if underscore_samples else 'none'}
"""

    Path(args.out).write_text(settings_r)
    print(f"[generate_spore_settings] Wrote {args.out}")


if __name__ == "__main__":
    main()